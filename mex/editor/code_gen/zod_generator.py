def _loc(name: str, index: SchemaIndex, shared: set[str]) -> tuple[str, ...]:
    """The file (as path segments) that declares `name`'s schema: the
    shared file if used by >1 bundle, otherwise its one owning bundle's
    single file."""
    return ("shared",) if name in shared else (index.owning_bundle(name),)


def _write_def_file(
    index: SchemaIndex,
    shared: set[str],
    results: dict[str, ZodResult],
    file_parts: tuple[str, ...],
    def_names: list[str],
    output_dir: Path,
    patterns: PatternRegistry,
    declare_patterns: set[str],
) -> Path:
    """Writes one file containing zero or more defs (topologically
    ordered so same-file references never point forward) plus whatever
    imports they need."""
    def_names = _topo_order(def_names, {n: results[n].def_refs for n in def_names})
    local = set(def_names)
    refs: set[str] = set()
    pattern_names: set[str] = set()
    for n in def_names:
        refs |= results[n].def_refs
        pattern_names |= results[n].pattern_names

    by_specifier: dict[str, set[str]] = {}
    if pattern_names and not declare_patterns:
        by_specifier.setdefault(import_specifier(file_parts, ("shared",)), set()).update(pattern_names)
    for ref in refs - local:
        by_specifier.setdefault(import_specifier(file_parts, _loc(ref, index, shared)), set()).add(f"{ref}Schema")

    imports = ['import { z } from "zod";']
    for spec, names in sorted(by_specifier.items()):
        imports.append(f'import {{ {", ".join(sorted(names))} }} from "{spec}";')

    body_parts = []
    if declare_patterns:
        lines = [
            f"{jsdoc('Regex pattern (deduplicated across every bundle).')}export const {n} = {json.dumps(p)};\n"
            for p, n in patterns.all_patterns().items()
            if n in declare_patterns
        ]
        body_parts.append("\n".join(lines) + "\n")
    body_parts += [results[n].code for n in def_names]

    return _write(output_dir, file_parts, "\n".join(imports) + "\n\n" + "".join(body_parts))


_UTILS_CODE = f"""\
{jsdoc("Runs `zodSchema` against the current field value and reports the first Zod issues as Angular Signal Forms validation errors.")}\
export function validateWithZod<T>(path: SchemaPath<T>, zodSchema: ZodType<T>): void {{
  validate(path, (ctx) => {{
    const result = zodSchema.safeParse(ctx.value());
    if (result.success) return null;
    return result.error.issues.map((issue) => ({{ kind: issue.code, message: issue.message }}));
  }});
}}

{jsdoc("Turns any Zod schema into an Angular Signal Forms schema function, ready to pass to schema<T>(...).")}\
export function zodFormSchema<T>(zodSchema: ZodType<T>) {{
  return (path: SchemaPathTree<T>) => validateWithZod(path as unknown as SchemaPath<T>, zodSchema);
}}
"""

def generate_zod_schemas(bundles: list[Bundle], output_dir: str | Path) -> list[Path]:
    """Generate everything: `shared.ts` (defs used by >1 bundle),
    `form-schemas.ts`, and one `{bundle}.ts` per bundle holding every def
    that bundle owns (its requested root models and anything it needs
    internally, together). Returns the written paths.
    """
    output_dir = Path(output_dir)
    index = build_schema_index(bundles)
    shared = index.shared_defs()
    patterns = PatternRegistry()
    results = {n: render_zod_schema(n, e, patterns) for n, e in index.defs.items()}
    written: list[Path] = []

    all_patterns = {p for r in results.values() for p in r.pattern_names}
    if shared or all_patterns:
        written.append(_write_def_file(index, shared, results, ("shared",), sorted(shared), output_dir, patterns, all_patterns))

    for bundle in bundles:
        owned = sorted(n for n in index.defs if index.owning_bundle(n) == bundle.name)
        written.append(_write_def_file(index, shared, results, (bundle.name,), owned, output_dir, patterns, set()))

    return written
