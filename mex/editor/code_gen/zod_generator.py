# pytypes.Node -> Zod expression
# ---------------------------------------------------------------------------


@dataclass
class ZodResult:
    """One def's generated Zod code, plus what it needs imported: other
    defs' schema constants (`def_refs`) and shared pattern constants
    (`pattern_names`)."""

    code: str = ""
    def_refs: set[str] = field(default_factory=set)
    pattern_names: set[str] = field(default_factory=set)


def _scalar_zod(node: ScalarNode, patterns: PatternRegistry, field_name: str | None, r: ZodResult) -> str:
    # Base type first, then chain on whatever constraints this scalar has.
    base = "z.boolean()" if node.py_type is bool else "z.number()" if node.py_type in (int, float) else "z.string()"
    if node.py_type is str and node.pattern:
        name = patterns.name_for(node.pattern, node.leaf_cls.__name__, field_name)
        r.pattern_names.add(name)
        base += f".regex(new RegExp({name}))"
    elif node.format == "email":
        base += ".email()"
    if node.py_type is str:
        if node.min_length is not None:
            base += f".min({node.min_length})"
        if node.max_length is not None:
            base += f".max({node.max_length})"
    if node.py_type in (int, float):
        if node.minimum is not None:
            base += f".min({node.minimum})"
        if node.maximum is not None:
            base += f".max({node.maximum})"
    return base


def zod_for_node(node: Node, patterns: PatternRegistry, r: ZodResult, field_name: str | None = None) -> str:
    """The Zod expression for one field's resolved node (recursive). A
    reference to another model is a union of a bare string (an id/
    reference) and the full embedded object -- the referenced model's own
    schema never carries that union itself, only field sites that point
    at it do."""
    if isinstance(node, ObjectRef):
        r.def_refs.add(node.cls.__name__)
        return f"{node.cls.__name__}Schema"
    if isinstance(node, EnumRef):
        r.def_refs.add(node.cls.__name__)
        return f"{node.cls.__name__}Schema"
    if isinstance(node, LiteralNode):
        return " ".join(f'z.literal("{v}")' if isinstance(v, str) else f"z.literal({v!r})" for v in node.values)
    if isinstance(node, ListNode):
        arr = f"z.array({zod_for_node(node.item, patterns, r, field_name)})"
        if node.min_length is not None:
            arr += f".min({node.min_length})"
        if node.max_length is not None:
            arr += f".max({node.max_length})"
        return arr
    if isinstance(node, UnionNode):
        scalars = [m for m in node.members if isinstance(m, ScalarNode)]
        if len(scalars) == len(node.members) and scalars and all(m.pattern for m in scalars):
            # Union of patterned scalars (e.g. YearMonthDay | YearMonth |
            # Year) -> try each regex in turn.
            parts = list(dict.fromkeys(_scalar_zod(m, patterns, field_name, r) for m in scalars))
            return parts[0] if len(parts) == 1 else f"z.union([{', '.join(parts)}])"
        return f"z.union([{', '.join(zod_for_node(m, patterns, r, field_name) for m in node.members)}])"
    if isinstance(node, ScalarNode):
        return _scalar_zod(node, patterns, field_name, r)
    return "z.unknown()"


def render_zod_schema(name: str, entry: DefEntry, patterns: PatternRegistry) -> ZodResult:
    """The `export const {name}Schema = ...` + `export type {name} =
    z.infer<...>` block for one def, each with its own `/** */` doc
    comment. Always a plain object/enum schema -- see `zod_for_node` for
    where the string-or-object union actually lives."""
    r = ZodResult()

    if isinstance(entry, EnumDef):
        values = ", ".join(f'"{m.value}"' for m in entry.cls)
        r.code = (
            f"{jsdoc(f'Zod schema for the {name} enum.')}"
            f"export const {name}Schema = z.enum([{values}]);\n\n"
            f"{jsdoc(f'TypeScript type inferred from {name}Schema.')}"
            f"export type {name} = z.infer<typeof {name}Schema>;\n\n"
        )
        return r

    fields: list[str] = []
    for f in entry.fields:
        z = zod_for_node(f.node, patterns, r, f.py_name)
        is_fixed_literal = isinstance(f.node, LiteralNode) and len(f.node.values) == 1
        if not is_fixed_literal:
            if f.nullable and not f.required:
                # pydantic dumps an unset Optional[X] field as explicit
                # JSON null, not a missing key -- .optional() alone only
                # covers "key absent", so a nullable-and-not-required
                # field needs BOTH allowed.
                z += ".nullish()"
            elif f.nullable:
                z += ".nullable()"
            elif not f.required:
                z += ".optional()"
        fields.append(f"  {f.alias}: {z},")

    body = "z.object({\n" + "\n".join(fields) + "\n})"
    doc = f"Zod schema for {name}."
    if entry.extends:
        r.def_refs.add(entry.extends)
        body = f"{entry.extends}Schema.extend({{\n" + "\n".join(fields) + "\n})"
        doc = f"Zod schema for {name} (extends {entry.extends})."

    r.code = (
        f"{jsdoc(doc)}"
        f"export const {name}Schema = {body};\n\n"
        f"{jsdoc(f'TypeScript type inferred from {name}Schema.')}"
        f"export type {name} = z.infer<typeof {name}Schema>;\n\n"
    )
    return r


