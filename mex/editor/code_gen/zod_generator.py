"""Written by Claude (Anthropic).

Renders the `pytypes` type IR as real Zod schemas and writes them to
disk. This is the only code-generation module -- one generator, one file.

Output layout (all flat under `output_dir`, no subfolders):

    shared.ts        # patterns + schemas for defs used by >1 bundle
    form-schemas.ts   # Angular Signal Forms adapters + one
                       # ...FormSchema export per requested entity
    {bundle}.ts        # everything that bundle owns -- its requested root
                        # models and anything it needs internally, together

Every field, including a reference to another model, matches its source
pydantic model strictly -- no relaxations like accepting a bare string in
place of a nested object.

Worth knowing before reading the rest: every file only ever references
defs from files that are fully evaluated before it runs (imports), except
within a single file, where JS `const` bindings are NOT hoisted: a schema
referencing another schema declared later in the *same* file throws
"Cannot access X before initialization" at runtime. `_topo_order()` exists
specifically to prevent that.
"""
# mypy: ignore-errors
from __future__ import annotations

import json
import posixpath
import re
from dataclasses import dataclass, field
from pathlib import Path

from .bundle import Bundle
from .patterns import PatternRegistry
from .pytypes import EnumRef, FieldSpec, ListNode, LiteralNode, Node, ObjectRef, ScalarNode, UnionNode
from .schema_collect import DefEntry, EnumDef, ModelDef, SchemaIndex, build_schema_index

SUFFIX = ".ts"
ESLINT_DISABLE = "/* eslint-disable @typescript-eslint/naming-convention */"
HEADER = "// AUTO-GENERATED by mex_form_codegen -- do not edit by hand."


def kebab(name: str) -> str:
    """PascalCase/camelCase -> kebab-case (Angular's file-naming default):
    `ExtractedActivity` -> `extracted-activity`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def jsdoc(text: str) -> str:
    """A `/** ... */` block comment -- every exported declaration gets one
    of these, never a `//` line comment."""
    return f"/**\n * {text}\n */\n"


def import_specifier(from_parts: tuple[str, ...], to_parts: tuple[str, ...]) -> str:
    """Relative TS import specifier (no extension, kebab-cased) between
    two files, each given as path segments (dirs..., filename) relative
    to the output root. Always starts with `./` or `../` -- a specifier
    without one of those is a bare/node_modules import, not a relative
    file path."""
    from_parts, to_parts = tuple(kebab(p) for p in from_parts), tuple(kebab(p) for p in to_parts)
    from_dir = posixpath.join(*from_parts[:-1]) if len(from_parts) > 1 else "."
    to_dir = posixpath.join(*to_parts[:-1]) if len(to_parts) > 1 else "."
    rel = posixpath.relpath(to_dir, start=from_dir)
    path = to_parts[-1] if rel == "." else f"{rel}/{to_parts[-1]}"
    return path if path.startswith(("./", "../")) else f"./{path}"


def _write(output_dir: Path, file_parts: tuple[str, ...], body: str) -> Path:
    text = f"{ESLINT_DISABLE}\n{HEADER}\n\n{body}"
    path = output_dir / Path(*(kebab(p) for p in file_parts)).with_suffix(SUFFIX)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def _topo_order(names: list[str], deps: dict[str, set[str]]) -> list[str]:
    """Order `names` so every name comes after whichever *other* names in
    `names` it depends on -- otherwise alphabetical, for a deterministic
    diff between runs. Prevents "used before declared" for same-file
    `const` references (see module docstring)."""
    names_set, seen, order = set(names), set(), []

    def visit(n: str, stack: set[str]) -> None:
        if n in seen or n in stack:  # already placed, or a cycle -- don't hang
            return
        stack = stack | {n}
        for dep in sorted(deps.get(n, ()) & names_set):
            visit(dep, stack)
        seen.add(n)
        order.append(n)

    for n in sorted(names):
        visit(n, set())
    return order


